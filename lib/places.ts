/*
 * Служебные слова убираются целиком, по словам, а не регуляркой: \b в JS
 * не видит кириллицу, а просмотр назад (?<!) ломает разбор скрипта в Safari
 * старше 16.4 — вместе со всей страницей.
 */
const STOP = new Set([
  'г', 'гор', 'город', 'пос', 'поселок', 'пгт', 'п', 'д', 'дер', 'деревня', 'с', 'село',
  'ул', 'улица', 'ленобласть', 'ленинградская', 'область', 'обл',
])

/** Сравнение без регистра, «ё», знаков и служебных слов. */
export function norm(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[-«»"',.()]/g, ' ')
    .split(/\s+/)
    .filter((w) => w && !STOP.has(w))
    .join(' ')
}
