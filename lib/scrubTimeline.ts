/** Зазор между соседними блоками — столько прокрутки поле стоит пустым. */
export const GAP = 0.03

export function assertSequential(bands: readonly Band[]): string | null {
  for (let i = 1; i < bands.length; i++) {
    const prev = bands[i - 1]
    const next = bands[i]
    if (next.from < prev.to) {
      return `участки пересекаются: ${prev.to} и ${next.from}`
    }
  }
  return null
}
