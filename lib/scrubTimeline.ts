/**
 * Расписание текстового поля залипающей секции.
 *
 * Первый экран и подписи занимают одно и то же место, поэтому их участки не
 * должны пересекаться ни на сотую: иначе уходящий текст просвечивает сквозь
 * приходящий. Между блоками оставлен зазор — короткая пауза, когда в поле
 * пусто и работает одна картинка.
 *
 * Правило простое: `to` предыдущего блока строго меньше `from` следующего.
 * Проверяется в assertSequential ниже, чтобы правка расписания не поехала молча.
 */

export type Band = { from: number; to: number }

/** Доля участка, за которую подпись выезжает и уезжает. */
export const ENTER = 0.22
export const EXIT = 0.18
/** Сдвиг второй строки — из-за него блок появляется лесенкой, а не целиком. */
export const STAGGER = 0.35
/** На столько строка приподнимается, выезжая снизу. */
export const RISE = 26

/**
 * Каждый блок стоит на своей высоте — там, где оказывается ползунок шкалы к
 * моменту, когда текст встал на место. Блоки выстраиваются лесенкой сверху
 * вниз: первый экран у самого верха, каждая следующая подпись ниже предыдущей.
 *
 * Отметка берётся не по началу участка, а по концу выезда: пока подпись
 * выезжает, она ещё приподнята на RISE, и привязка к самому началу оставляла бы
 * ползунок выше строки на всю эту высоту.
 */
export const anchorOf = (band: Band) =>
  band.from + (band.to - band.from) * ENTER

/**
 * Опорные точки подписи: когда заголовок и абзац выехали и когда начинают
 * уходить. Одни и те же числа нужны самой подписи (components/scrub/ScrubCaption)
 * и свету фары за ней (HeadlightWindow) — поэтому считаются в одном месте.
 */
export function captionKeys({ from, to }: Band) {
  const span = to - from
  const enterEnd = from + span * ENTER
  return {
    enterEnd,
    exitStart: to - span * EXIT,
    textFrom: from + span * ENTER * STAGGER,
    textEnterEnd: enterEnd + span * ENTER * STAGGER,
  }
}

/** Непрозрачность заголовка подписи в точке прокрутки — как у useTransform в ScrubCaption. */
export function titleOpacityAt(p: number, band: Band): number {
  const { enterEnd, exitStart } = captionKeys(band)
  if (p <= band.from || p >= band.to) return 0
  if (p < enterEnd) return (p - band.from) / (enterEnd - band.from)
  if (p > exitStart) return (band.to - p) / (band.to - exitStart)
  return 1
}

