'use client'

import { useEffect } from 'react'
import { useMotionValue, type MotionValue } from 'motion/react'

/**
 * Плавный прогресс секции: одно значение, которое догоняет прокрутку с
 * инерцией, и от него живёт всё, что видно в залипающем кадре, — время клипа,
 * текст, ползунок шкалы, наезд и затемнение.
 *
 * Зачем. Щелчок колеса — это 100 px, то есть 3,5% сцены разом. Раньше клип
 * догонял его за треть секунды, а текст менялся за один кадр: первый экран
 * терял 30% яркости, подпись проступала наполовину. На глаз — «щёлкнул, и всё
 * резко произошло». Теперь щелчок раскатывается на ~0,6 с с плавным
 * торможением, и клип с текстом едут одной величиной, а не каждый сам по себе.
 *
 * Считается по времени, а не по кадрам. Прежнее сглаживание клипа съедало
 * долю остатка за кадр, и на мониторе 144 Гц догоняло в 2,4 раза быстрее, чем
 * на 60 Гц, — то есть было резче ровно у тех, у кого экран лучше.
 *
 * Сама страница прокручивается как обычно, без подмены колеса: прокрутка
 * остаётся родной (клавиатура, полоса, якоря, экранные читалки работают как
 * везде), а сглаживается только то, что внутри залипающего кадра.
 */

/** Постоянная времени догоняния: за неё проходится ~63% остатка пути. */
const TAU = 0.2

/**
 * Доводка на подъезде: скорость не ниже BRAKE·остаток^¾ (доли сцены в
 * секунду). Экспонента к цели не приходит никогда, а степень ¾ доводит до
 * полной остановки за конечное время, и замедление к концу само сходит на нет
 * (оно ∝ √остатка) — без обрыва в момент остановки.
 *
 * История — что владелец видел на щелчке колеса (8 кадров клипа):
 * - корень (∝ √остатка) с силой 0,6: клип вставал, ещё едучи 5 кадров/с за 0,1 с
 *   до остановки, замедление обрывалось в ноль — «немного резко, с рывком»;
 * - корень 0,15: конец плавный (0,5 кадра/с за 0,1 с до остановки), но последний
 *   кадр растворялся ~0,7 с и картинка замирала через 1,03 с — «слишком долго
 *   тормозит и смазывает кадры, особенно на дворниках»;
 * - корень 0,3 и растворение только в середине промежутка: замирала через
 *   0,61 с, но — «опять резко, с рывком» (на медленном ходу кадр стоял, потом
 *   быстро сменялся: ступеньки). Растворение вернули на весь промежуток.
 *
 * Сейчас — степень ¾ с силой 1,8. Замер в Chrome на щелчок колеса
 * (scripts/probe-brake.mjs), картинка замирает / двоение / скорость за 0,1 с
 * до замирания:
 *   корень 0,15 (плавно, долго)      1,02 с  0,58 с  0,5 кадра/с
 *   корень 0,3 + узкое растворение   0,61 с  0,17 с  7,3 кадра/с  (резко)
 *   степень ¾, 1,8 (сейчас)          0,73 с  0,39 с  1,0 кадра/с
 * Начало щелчка — та же экспонента TAU. Если снова резко — сила 1,6
 * (0,80 с, 0,9 кадра/с по модели); если долго — 2,0 (0,65 с, 1,6 кадра/с).
 */
const BRAKE = 1.8
const BRAKE_POW = 0.75

/** Ближе этого к цели — доехали; цикл останавливается и ничего не стоит. */
const SETTLED = 0.00005

/**
 * Скачок одним событием больше этой доли — не прокрутка, а прыжок:
 * перезагрузка посреди секции, переход по якорю, Home/End без плавной
 * прокрутки. Догонять его на глазах незачем — встаём на место сразу.
 * Колесо, трекпад, PageDown и полоса прокрутки приходят многими мелкими
 * событиями и сюда не попадают.
 */
const JUMP = 0.25

/** Вкладку вернули из фона — не проматывать накопленное за паузу разом. */
const MAX_DT = 0.05

export function useSmoothProgress(
  source: MotionValue<number>,
  /** false при prefers-reduced-motion: тогда значение повторяет прокрутку как есть. */
  enabled: boolean,
  /**
   * На сколько равных шагов делится ход — у сцены с клипом это число кадров
   * минус один. Цель округляется до шага, и движение всегда останавливается
   * ровно на целом кадре: промотка растворяет соседние кадры друг в друга, и
   * остановка между ними оставила бы на экране двоение. Текст и шкала от
   * этого сдвигаются не больше чем на полкадра — 0,2% хода, глазом не видно.
   * 0 — без округления (пока длина клипа неизвестна).
   */
  steps = 0,
): MotionValue<number> {
  const smooth = useMotionValue(source.get())

  useEffect(() => {
    const snap = (v: number) => (steps > 0 ? Math.round(v * steps) / steps : v)

    smooth.set(snap(source.get()))
    if (!enabled) return source.on('change', (v) => smooth.set(v))

    let raf = 0
    let last = 0
    let current = snap(source.get())
    let lastTarget = source.get()

    const tick = (now: number) => {
      const target = snap(source.get())
      const dt = last ? Math.min((now - last) / 1000, MAX_DT) : 1 / 60
      last = now

      const delta = target - current
      const distance = Math.abs(delta)
      const step = Math.min(
        distance,
        Math.max(distance * (1 - Math.exp(-dt / TAU)), BRAKE * Math.pow(distance, BRAKE_POW) * dt),
      )
      current += Math.sign(delta) * step
      if (Math.abs(target - current) < SETTLED) current = target
      smooth.set(current)

      if (current === target) {
        raf = 0
        last = 0
        return
      }
      raf = requestAnimationFrame(tick)
    }

    const unsubscribe = source.on('change', (v) => {
      const jump = Math.abs(v - lastTarget) > JUMP
      lastTarget = v
      if (jump) {
        cancelAnimationFrame(raf)
        raf = 0
        last = 0
        current = snap(v)
        smooth.set(current)
        return
      }
      if (!raf) raf = requestAnimationFrame(tick)
    })

    return () => {
      unsubscribe()
      cancelAnimationFrame(raf)
    }
  }, [source, smooth, enabled, steps])

  return smooth
}
