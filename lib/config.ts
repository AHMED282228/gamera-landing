/**
 * Подкаталог, в котором лежит сайт. Пусто — значит в корне домена, и это
 * рабочий случай: на evakuator-gamera.ru сайт стоит в корне.
 *
 * Непусто он бывает только у витрины на GitHub Pages: там проектная страница
 * живёт по адресу вида user.github.io/имя-репозитория/, и все абсолютные пути
 * без приставки ведут в никуда. Приставку подставляет сборка, переменной
 * NEXT_PUBLIC_BASE_PATH.
 *
 * Свои файлы Next префиксует сам по basePath из next.config.mjs. А вот пути,
 * написанные строками — постер, клипы, логотип, — не префиксует никто: он их
 * просто не видит. Поэтому они все собраны здесь и проходят через asset().
 */
export const BASE_PATH = process.env.NEXT_PUBLIC_BASE_PATH ?? ''

const asset = (path: string) => `${BASE_PATH}${path}`

