/**
 * Ссылка в бота.
 *
 * Здесь ?start=, а не ?startapp=, и это осознанный выбор, а не упрощение.
 *
 *   ?start=    открывает переписку с ботом. Работает у любого бота всегда.
 *   ?startapp= открывает мини-приложение сразу, минуя переписку, — но только
 *              если в BotFather у бота задано главное мини-приложение
 *              (Bot Settings → Configure Mini App). Если оно не задано,
 *              человек со сломавшейся машиной упирается в ошибку.
 *
 * На странице t.me/evakuator_spb_bot сейчас видна кнопка «Start Bot», а не
 * «Launch App» — значит главное мини-приложение не назначено, и ?startapp
 * ставить рано. Как только оно появится, здесь меняется одно слово, и форма
 * начнёт открываться в одно касание вместо двух.
 *
 * Вести на https://evakuator-gamera.ru/webapp/ напрямую нельзя ни при каком
 * раскладе: в обычном браузере мини-приложение остаётся без данных Telegram
 * и заявка никуда не уходит.
 */
