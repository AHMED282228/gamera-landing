/**
 * Детали эвакуатора на кадрах обзора (tour-a/b/c-2752.webp) — для показа по
 * нажатию (components/sections/Truck.tsx). Координаты — доли ширины и высоты
 * кадра 16:9. Контуры сняты 15 ноября 2026 по самому кадру 2752 px: края — по
 * перепаду яркости поперёк кромки (±1–2 px), прямые кромки — подгонкой прямой.
 *
 * shape — контур детали: по нему деталь «отделяется» (копия кадра, обрезанная
 * этим контуром, чуть приподнимается с тенью, остальное темнеет) и по нему
 * прочерчивается обводка. cam — куда встаёт камера: точка кадра в «прицеле»
 * и приближение (1 — кадр во всю ширину).
 */

export type TourPhoto = 'a' | 'b' | 'c'
export type Pt = readonly [number, number]

/**
 * Ремень через колесо — готовый слой поверх снимка (scripts в tourParts-комментарии):
 * лента на протекторе в перспективе, со светотенью и фактурой; за шиной скрыт, а где
 * его заслоняет кузов — кузов в окне прозрачный («рентген»): видна скрытая часть шины
 * и ремень на ней. Проявляется по кругу от переднего крюка через верх к заднему.
 */
export type StrapImg = {
  /** Ключ картинки в TOUR_MEDIA. */
  media: 'strapRear' | 'strapFront'
  /** Рамка слоя: x0, y0, x1, y1 — доли кадра. */
  box: readonly [number, number, number, number]
  /** Центр разворота маски — доли рамки слоя; от какого угла и на сколько (° , 0 — вверх). */
  at: Pt
  from: number
  sweep: number
  /**
   * Обводка, как у других деталей: края ленты по геометрии колеса (ровные дуги и
   * прямые), торцы — вокруг крюков (доли кадра). Где лента уходит за шину, линия
   * открыта — ремень там не кончается.
   */
  edge: Pt[][]
}

export type TourPart = {
  id: 'overview' | 'deck' | 'winch' | 'ramps' | 'wheels' | 'chocks'
  photo: TourPhoto
  cam: { x: number; y: number; z: number }
  /** Контуры детали (у аппарелей и колёс — по два). Пусто — общий вид. */
  shapes: Pt[][]
  /**
   * От какой точки растёт каждый контур при подъёме (по умолчанию — от своей
   * середины). Точка на внутренней кромке держит её на месте: иначе из-под
   * приподнятой копии выглядывает край оригинала.
   */
  anchors?: Pt[]
  /** Насколько деталь крупнее при подъёме (по умолчанию 0,03). */
  grow?: number
  /**
   * Затемнение вокруг детали в её «пятне» (0–1, по умолчанию 0,2). Тёмной детали на
   * тёмном фоне — сильнее: кузов вокруг колеса уходит в тень, колесо со снимка видно.
   */
  dim?: number
  /** Тонкая деталь: обводка и свечение тоньше, чтобы не закрывали её саму. */
  fine?: boolean
  /**
   * Фокус, как у объектива: деталь остаётся точно на месте (не приподнимается —
   * у тонкой детали подъём на 5 px открывал оригинал под ней), фон кадра мягко
   * размывается и темнеет, деталь — резкая и светлее.
   */
  focus?: boolean
  /** false — без обводки (тёмное колесо в тёмной арке обводится только кольцом). */
  outline?: boolean
  /**
   * Мягкий прожектор вместо выреза по контуру: резкая копия и просвет в затемнении
   * — эллипсом по рамке контура с растушёвкой. Для тёмной детали без видимых краёв
   * (колесо в арке): жёсткий край выреза на ней читается как наклейка.
   */
  soft?: boolean
  /** Во сколько раз светлее приподнятая деталь (тёмную лебёдку — сильнее). */
  light?: number
  /** Трос: линия по кадру от детали — прочерчивается после контура. */
  cable?: Pt[]
  /**
   * Точки-кнопки детали на кадрах, где она видна (нажал — камера летит к ней).
   * Точка на своём кадре (spots[photo]) — ещё и начало выноски к карточке.
   */
  spots: Partial<Record<TourPhoto, Pt>>
  /** Ремни — слоями поверх снимка; подпись — у вершины ремня (tagAt). */
  strapImgs?: StrapImg[]
  tagAt?: Pt
  /** Яркость по контурам, если у них разная (переднее колесо в тени — светлее). */
  shapeLight?: number[]
  /** Откуда начинается линия к сноске (иначе — от точки детали на её кадре). */
  wireAt?: Pt
  /** Своя подпись точки на кадре (иначе — label из TRUCK_TOUR). */
  spotLabel?: Partial<Record<TourPhoto, string>>
}

