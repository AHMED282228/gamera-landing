import type { MetadataRoute } from 'next'
import { SITE_URL } from '@/lib/config'

/**
 * sitemap.xml — список страниц сайта для поисковиков.
 *
 * Зачем он на одностраничнике. Робот и так найдёт единственную страницу — по
 * ссылке с домена. Польза здесь в другом: пока сайт новый и на него никто не
 * ссылается, роботу неоткуда узнать, что он вообще появился. Карта, указанная в
 * robots.txt и добавленная в панель вебмастера, — самый короткий способ сказать
 * «вот я, приходите».
 *
 * Второе: по дате изменения робот решает, приходить ли снова. Без карты он
 * судит по своим догадкам и на редко обновляемом сайте начинает заходить раз в
 * несколько недель.
 *
 * priority на одностраничнике смысла не имеет: он расставляет вес между
 * страницами одного сайта, а страница здесь одна. Ставлю 1 и не выдумываю
 * иерархию из ничего.
 *
 * Дата проставляется на сборке и потом не меняется — сайт статический, сервера,
 * который пересчитал бы её на лету, нет. Это и правильно: «изменено» здесь
 * означает «пересобрано и выложено», а именно это роботу и нужно знать.
 */
export const dynamic = 'force-static'

export default function sitemap(): MetadataRoute.Sitemap {
  return [
    {
      url: SITE_URL,
      lastModified: new Date(),
      changeFrequency: 'monthly',
      priority: 1,
    },
  ]
}
