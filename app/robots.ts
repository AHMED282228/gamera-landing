import type { MetadataRoute } from 'next'
import { SITE_URL } from '@/lib/config'

/**
 * robots.txt — записка для поисковых роботов.
 *
 * Робот, придя на сайт, первым делом запрашивает /robots.txt и смотрит, что
 * ему разрешено обходить. Файла нет — робот получает 404 и обходит всё подряд;
 * ошибкой это не считается, но остаётся неясность, а неясность на новом домене
 * лишняя.
 *
 * Здесь разрешено всё: на сайте одна страница и прятать нечего. Настоящая
 * работа этого файла — последняя строка со ссылкой на карту сайта. Яндекс и
 * Google ищут карту именно тут, и без этой строки её приходится либо угадывать,
 * либо добавлять руками в панели вебмастера.
 *
 * Next собирает файл сам при сборке: app/robots.ts превращается в /robots.txt
 * в готовой статике.
 *
 * force-static обязателен при `output: export`: без него Next считает маршрут
 * динамическим, ждёт сервера и роняет сборку с ошибкой про force-static.
 */
export const dynamic = 'force-static'

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [{ userAgent: '*', allow: '/' }],
    sitemap: `${SITE_URL}/sitemap.xml`,
    host: SITE_URL,
  }
}
